def gallery(items: list[dict]) -> None:
    present = {i["group"] for i in items}
    options = "".join(f'<option value="{k}">{v}</option>' for k, v in FAMILIES.items() if k in present)
    data = json.dumps(items, ensure_ascii=False).replace("</", "<\\/")
    page = (PAGE.replace("__DATA__", data).replace("__OPTIONS__", options).replace("__COUNT__", str(len(items)))
            .replace("__ISSUES__", f"{REPO_URL}/issues"))
    write(ROOT / "START_HERE.html", page)


def summary(rows: list[dict], states: dict[str, dict], items: list[dict]) -> None:
    data = {
        "tickets": len(rows),
        "production_status": dict(Counter(s["production_status"] for s in states.values())),
        "release_status": dict(Counter(s["release_status"] for s in states.values())),
        "produced_by_family": dict(Counter(family(r) for r in rows if states[r["id"]]["production_status"] == "produced")),
        "gallery_assets": len(items),
        "mp4_files": len(list((ROOT / "assets").glob("*/*/exports/*.mp4"))),
        "issues_recorded": sum(bool(r.get("github_issue")) for r in rows),
    }
    write(ROOT / "review/summary.json", json.dumps(data, indent=2) + "\n")
    print(json.dumps(data, indent=2))


def main() -> int:
    manifest = load(ROOT / "manifest.json")
    rows = manifest["tickets"]
    states = {r["id"]: load(ROOT / r["asset_dir"] / "state.json") for r in rows}
    asset_index(rows, states)
    remaining(rows, states, manifest)
    items = gallery_items(rows, states)
    gallery(items)
    summary(rows, states, items)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
