"""Rebuild the repository indexes from manifest.json and every asset's state.json.

Writes START_HERE.html (offline gallery of produced assets), asset_index.csv, review/REMAINING_TICKETS.md and
review/summary.json. Never writes inside an asset folder; gallery thumbnails go to review/gallery/.

  python tools/build_indexes.py
"""
