def load(path: Path):
    return json.loads(path.read_bytes().decode("utf-8"))


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))


def family(row: dict) -> str:
    return row["asset_dir"].split("/")[1]


def issue_link(number: int | None, prefix: str = "") -> str:
    return f"[#{number}]({REPO_URL}/issues/{number})" if number else ""


def asset_index(rows: list[dict], states: dict[str, dict]) -> None:
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(["id", "title", "family", "kind", "lane", "original_family", "script_sections", "dependencies",
                     "release_gates", "asset_dir", "ticket", "github_issue", "production_status", "release_status"])
    for r in rows:
        s = states[r["id"]]
        writer.writerow([r["id"], r["title"], family(r), r["kind"], r["lane"], r["parent"],
                         ",".join(map(str, r["sections"])), ",".join(r["deps"]), ",".join(r["gates"]), r["asset_dir"],
                         r["ticket"], r.get("github_issue", ""), s["production_status"], s["release_status"]])
    write(ROOT / "asset_index.csv", out.getvalue())


def remaining(rows: list[dict], states: dict[str, dict], manifest: dict) -> None:
    lines = ["# Remaining tickets", "",
             "Generated by `python tools/build_indexes.py` from each asset's `state.json`. GitHub issues are the tracker: "
             f"[open issues]({REPO_URL}/issues).", ""]

    def entry(r: dict, extra: str = "") -> str:
        issue = issue_link(r.get("github_issue"))
        return (f"- [{r['id']} — {r['title']}](../{r['ticket']})" + (f" · {issue}" if issue else "")
                + (f" · {extra}" if extra else ""))

    in_progress = [r for r in rows if states[r["id"]]["production_status"] == "in_progress"]
    if in_progress:
        lines += ["## In progress", ""] + [entry(r) for r in in_progress] + [""]
    planned = [r for r in rows if states[r["id"]]["production_status"] in ("planned", "blocked")]
    lines += ["## Not started", ""]
    for kind in ["support", "archive", "scout", "still", "capture", "motion", "code"]:
        group = [r for r in planned if r["kind"] == kind]
        if group:
            lines += [f"### {kind.title()}", ""] + [entry(r, "waiting on " + ", ".join(
                d for d in r["deps"] if states[d]["production_status"] not in ("produced", "reviewed"))
                if any(states[d]["production_status"] not in ("produced", "reviewed") for d in r["deps"]) else "")
                for r in group] + [""]
    review = [r for r in rows if states[r["id"]]["production_status"] == "produced" and states[r["id"]]["release_status"] != "approved"]
    lines += ["## Produced, release not yet approved", "",
              f"{len(review)} produced assets still need a producer release decision. Open editorial gates are listed; "
              "an asset with no gates only needs the producer's approval.", ""]
    lines += [entry(r, ("gates " + ", ".join(r["gates"])) if r["gates"] else "no gates") for r in review] + [""]
    lines += ["## Human / capability handoffs", ""]
    for path in sorted((ROOT / "docs/handoffs").glob("H*.md")):
        title = path.read_bytes().decode("utf-8").splitlines()[0].lstrip("# ").strip()
        issue = issue_link(manifest.get("handoff_issues", {}).get(path.stem))
        lines.append(f"- [{title}](../docs/handoffs/{path.name})" + (f" · {issue}" if issue else ""))
    write(ROOT / "review/REMAINING_TICKETS.md", "\n".join(lines) + "\n")


def gallery_items(rows: list[dict], states: dict[str, dict]) -> list[dict]:
    items = []
    thumbs = ROOT / "review/gallery"
    thumbs.mkdir(parents=True, exist_ok=True)
    for r in rows:
        s = states[r["id"]]
        if s["production_status"] != "produced" or r["kind"] == "support":
            continue
        base = ROOT / r["asset_dir"]
        poster = next((base / p for p in ["exports/poster.png", "exports/framed.png"] if (base / p).exists()), None)
        if poster is None:
            print(f"warning: {r['id']} has no poster PNG; left out of the gallery")
            continue
        rel = lambda p: p.relative_to(ROOT).as_posix()
        thumb = thumbs / f"{r['id']}.jpg"
        image = Image.open(poster).convert("RGB")
        image.thumbnail((640, 360), Image.Resampling.LANCZOS)
        canvas = Image.new("RGB", (640, 360), "#08090c")
        canvas.paste(image, ((640 - image.width) // 2, (360 - image.height) // 2))
        canvas.save(thumb, quality=86, optimize=True)
        delivery = load(base / "delivery.json") if (base / "delivery.json").exists() else {}
        variants = []
        for png in sorted((base / "exports").glob("*.png")):
            if png.name == "contact-sheet.png":
                continue
            mp4, svg = base / "exports" / f"{png.stem}.mp4", base / "src" / f"variant-{png.stem}.svg"
            variants.append({"name": png.stem, "png": rel(png), "mp4": rel(mp4) if mp4.exists() else None,
                             "svg": rel(svg) if svg.exists() else None})
        video = base / "exports/preview.mp4"
        source = base / "src/index.html"
        items.append({
            "id": r["id"], "title": r["title"], "group": family(r), "poster": rel(poster), "thumb": rel(thumb),
            "video": rel(video) if video.exists() else None, "source": rel(source) if source.exists() else None,
            "ticket": r["ticket"], "issue": f"{REPO_URL}/issues/{r['github_issue']}" if r.get("github_issue") else None,
            "qa": rel(base / "qa.md") if (base / "qa.md").exists() else None,
            "duration_seconds": delivery.get("duration_seconds"), "gates": delivery.get("unresolved_gates", r["gates"]),
            "release": s["release_status"], "variants": variants})
    return items


